CONTROL = {"if", "elseif", "else", "endif", "continue if", "pause while"}


def _verb_match(line: str) -> tuple[str, str] | None:
    """The verb rule that takes ``line``'s first word(s), and what it took."""
    for name in ("control", "command"):
        match = _rule(name).match(line)
        if match:
            return name, match.group(1)
    return None


@pytest.mark.parametrize("case", ["lower", "upper", "title"])
def test_every_verb_is_colored_at_line_start_in_any_case(case: str) -> None:
    for verb in _verbs():
        if verb in {"createfile until", "appendfile", "override run", "override wait"}:
            continue  # rules of their own, below
        written = getattr(verb, case)()
        for line in (written, f"  {written} x", f"\t{written}"):
            found = _verb_match(line)
            assert found is not None, line
            rule, taken = found
            assert " ".join(taken.lower().split()) == verb, (line, taken)
            assert rule == ("control" if verb in CONTROL else "command"), line


def test_a_multi_word_verb_wins_over_its_first_word() -> None:
    assert _verb_match("action log command x") == ("command", "action log command")
    assert _verb_match("download now as x.exe http://x") == ("command", "download now as")
    assert _verb_match("setting delete x") == ("command", "setting delete")


def test_extra_spaces_between_a_verbs_words_still_match() -> None:
    found = _verb_match("download  now   as x")
    assert found is not None and " ".join(found[1].split()) == "download now as"


def test_a_verb_is_never_a_prefix_of_a_longer_word() -> None:
    """The defect in bigfix/highlight-bigfix-actionscript: `runner` colored `run`."""
    assert _verb_match("runner x") is None
    assert _verb_match("ifx") is None
    assert _verb_match("runhidden x") == ("command", "runhidden")


def test_a_verb_is_matched_only_at_line_start() -> None:
    for line in ("x run y", "// run y", '"run" y', "{run} y"):
        assert _verb_match(line) is None, line


def test_a_condition_written_against_its_keyword_still_colors_the_keyword() -> None:
    """`if{...}`, `continue if{...}`: real content writes both spacings."""
    assert _verb_match("if{exists file 'x'}") == ("control", "if")
