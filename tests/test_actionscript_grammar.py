"""The ActionScript and BES XML highlighting grammars (issue #116).

Generated by ``tools/generate_tmlanguage.py`` from a committed verb list
(``tools/data/actionscript_verbs.txt``) and the extractor's own tables. These
tests read the grammars' regexes with Python's ``re``, which is close to, but
not, the Oniguruma engine VS Code runs: they catch logic errors (which words a
rule takes, where it stops), not engine quirks. Each TextMate ``(?:^|\\G)``
anchor is read as ``^``.

The rule that matters most in a ``.bes`` file: no ActionScript rule runs past
a ``]]>`` or ``</ActionScript>``, so a broken body can never color the rest of
the file. Every single-line rule is checked against that below.
"""

from __future__ import annotations

