def test_an_override_block_holds_only_option_lines() -> None:
    rule = _repository()["override"]
    begin, end = _python(rule["begin"]), _python(rule["end"])
    assert begin.match("override wait") and begin.match("Override Run")
    for line in ("hidden=true", "  completion = job", "RunAs=currentuser", "timeout_seconds={x}"):
        assert not end.match(line), line
    for line in ("wait cmd.exe", "run x=y", "]]></ActionScript>", "hidden"):
        assert end.match(line), line
    # Blank and comment lines pass through, as pre-commit-bigfix's lint reads
