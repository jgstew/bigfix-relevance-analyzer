REPO_ROOT = Path(__file__).resolve().parent.parent
GENERATOR = REPO_ROOT / "tools" / "generate_tmlanguage.py"
KEYWORD_GENERATOR = REPO_ROOT / "tools" / "generate_actionscript_keywords.py"
VERBS = REPO_ROOT / "tools" / "data" / "actionscript_verbs.txt"

HOST_END = "]]></ActionScript>"


@functools.cache
def _generator() -> Any:
    return load_tool(GENERATOR, "_generate_tmlanguage")


def _verbs() -> list[str]:
    return [
        line for line in VERBS.read_text("utf-8").splitlines() if line and not line.startswith("#")
    ]


def _python(pattern: str) -> re.Pattern[str]:
    r"""A grammar regex for Python's `re`: `\G` only ever appears as `(?:^|\G)`."""
    assert pattern.count(r"\G") == pattern.count(r"(?:^|\G)"), pattern
    return re.compile(pattern.replace(r"(?:^|\G)", "^"))


@functools.cache
def _grammar() -> dict[str, Any]:
    grammar: dict[str, Any] = _generator().actionscript_grammar()
    return grammar


def _repository() -> dict[str, Any]:
    repository: dict[str, Any] = _grammar()["repository"]
    return repository


@functools.cache
def _rule(name: str) -> re.Pattern[str]:
    return _python(_repository()[name]["match"])


def _scan(line: str, names: list[str] | None = None) -> list[tuple[str, str]]:
    """``(rule, text)`` for each single-line rule match on ``line``, the way
    TextMate picks them: the earliest match wins, ties go to the rule listed
    first, and scanning resumes where the match ended."""
    grammar = _grammar()
    repository = grammar["repository"]
    if names is None:
        names = [include["include"].removeprefix("#") for include in grammar["patterns"]]
    rules = [(name, _rule(name)) for name in names if "match" in repository[name]]
    found: list[tuple[str, str]] = []
    position = 0
    while position < len(line):
        best: tuple[int, int, str, re.Match[str]] | None = None
        for order, (name, rule) in enumerate(rules):
            match = rule.search(line, position)
            if match is None or match.end() == match.start():
                continue
            key = (match.start(), order)
            if best is None or key < (best[0], best[1]):
                best = (match.start(), order, name, match)
        if best is None:
            break
        found.append((best[2], best[3].group()))
        position = best[3].end()
    return found


